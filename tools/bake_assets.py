ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'clock-assets'
KINDS=['hour','minute','second','static1','static2']
IMPORTED=['aviator-eyl2', 'untitled-theme-ldbl', 'untitled-theme-k5p7', 'untitled-theme-pz45', 'steam-punk-t2is', 'untitled-theme-9wk0']

def rgb565(r,g,b):return ((r&248)<<8)|((g&252)<<3)|(b>>3)
def ink(value):return rgb565(value>>16,(value>>8)&255,value&255)
def array(out,ctype,name,values):
    out.write(f'alignas(4) const {ctype} {name}[] PROGMEM = {{\n')
    for i in range(0,len(values),32):out.write(','.join(map(str,values[i:i+32]))+',\n')
    out.write('};\n')

def windows_font(file,size):
    font=ImageFont.truetype('C:/Windows/Fonts/'+file,size);glyphs=[];pixels=[]
    for code in range(32,127):
        ch=chr(code);left,top,right,bottom=font.getbbox(ch,anchor='ls');w,h=right-left,bottom-top
        image=Image.new('L',(max(1,w),max(1,h)))
        if w and h:ImageDraw.Draw(image).text((-left,-top),ch,font=font,fill=255,anchor='ls')
        glyphs.append((len(pixels),w,h,round(font.getlength(ch)),left,top))
        if w and h:pixels.extend(image.tobytes())
    ascent,descent=font.getmetrics()
    return glyphs,pixels,round((ascent-descent)/2),ascent+descent

def emit_font(out,name,content):
    glyphs,pixels,baseline,height=content
    array(out,'uint8_t',name+'Pixels',pixels)
    out.write(f'const Glyph {name}Glyphs[] PROGMEM = {{\n')
    for glyph in glyphs:out.write('{'+','.join(map(str,glyph))+'},\n')
    out.write('};\n'+f'const Font {name}Font={{{name}Pixels,{name}Glyphs,{baseline},{height}}};\n')

def glow_font(content,radius):
    """Bake the original three-ring glow once rather than paint 24 passes per tick."""
    glyphs,pixels,baseline,height=content;result=[];alpha=[]
    directions=[(1,0),(-1,0),(0,1),(0,-1),(.707,.707),(-.707,.707),(.707,-.707),(-.707,-.707)]
    for offset,w,h,advance,left,top in glyphs:
        if not w or not h:result.append((len(alpha),0,0,advance,left,top));continue
        source=Image.frombytes('L',(w,h),bytes(pixels[offset:offset+w*h]));size=(w+2*radius,h+2*radius)
        glow=Image.new('L',size)
        for ring in range(1,4):
            reach=round(radius*ring/3);strength=90//ring
            reduced=source.point(lambda a:a*strength//255)
            for dx,dy in directions:
                layer=Image.new('L',size);layer.paste(reduced,(radius+round(dx*reach),radius+round(dy*reach)))
                glow=ImageChops.invert(ImageChops.multiply(ImageChops.invert(glow),ImageChops.invert(layer)))
        result.append((len(alpha),size[0],size[1],advance,left-radius,top-radius));alpha.extend(glow.tobytes())
    return result,alpha,baseline,height

class Baker:
    def __init__(self,out,packed):self.out=out;self.packed=packed;self.total=0
    def blob(self,name,raw):
        data=zlib.compress(raw,9) if self.packed else raw
        if self.packed:assert zlib.decompress(data)==raw
        array(self.out,'uint8_t',name,list(data));self.total+=len(data)
        return '{'+f'{name},{len(data)},{len(raw)}'+'}'
    def sprite(self,folder,name,meta,symbol):
        path=folder/name
        if not path.exists() or not meta.get('show',False):return '{{nullptr,0,0},0,0,0,0,233,233,0}'
        im=Image.open(path).convert('RGBA');box=im.getchannel('A').getbbox()
        if not box:return '{{nullptr,0,0},0,0,0,0,233,233,0}'
        im=im.crop(box);raw=bytearray()
        for r,g,b,a in im.getdata():
            c=rgb565(r,g,b);raw.extend((c&255,c>>8,a))
        blob=self.blob(symbol,bytes(raw))
        return '{'+f'{blob},{im.width},{im.height},{meta.get("pivotX",0)-box[0]},{meta.get("pivotY",0)-box[1]},{meta.get("centerX",233)},{meta.get("centerY",233)},{meta.get("blend",0)}'+'}'

def build(packed):
    destination=ROOT/'src/assets.cpp' if packed else ROOT/'tools/generated/assets_host.cpp'
    destination.parent.mkdir(exist_ok=True)
    credits=[];descriptors=[]
    with destination.open('w',encoding='utf-8',newline='\n') as out:
        out.write('// Generated by tools/bake_assets.py.\n#include <Arduino.h>\n#include "assets.h"\n')
        baker=Baker(out,packed)
        for i,slug in enumerate(['meridian-midnight-rose','meridian-brass-silver-rose']+IMPORTED):
            folder=(SOURCE if i<2 else ROOT/'imported-faces')/slug
            style=json.loads((folder/'clock_style.json').read_text(encoding='utf-8'))
            manifest=json.loads((folder/'theme.json').read_text(encoding='utf-8'))
            label=['Meridian Midnight','Meridian Brass & Parchment'][i] if i<2 else manifest['name'].strip('⚙ ')
            credits.append({'name':label,'author':manifest.get('author',''),'license':manifest.get('license','Not specified; personal device copy'),'source_slug':slug})
            im=Image.open(folder/'clock_plate.png').convert('RGBA');assert im.size==(466,466)
            bg=style.get('bg',0);base=Image.new('RGBA',im.size,(bg>>16,(bg>>8)&255,bg&255,255));base.alpha_composite(im)
            raw=bytearray()
            for p in base.convert('RGB').getdata():c=rgb565(*p);raw.extend((c&255,c>>8))
            plate=baker.blob(f'plate{i}',bytes(raw));sprites=[];shadows=[]
            hand=style.get('hands',{});shadow=hand.get('shadow',{})
            for kind in KINDS:
                filename=f'clock_hand_{kind}.png' if kind in KINDS[:3] else f'clock_{kind}.png'
                sprites.append(baker.sprite(folder,filename,hand.get(kind,{}),f'face{i}_{kind}'))
            for kind in KINDS[:3]:
                meta=dict(hand.get(kind,{}));meta['show']=meta.get('show',False) and shadow.get('on',False)
                meta['centerX']=meta.get('centerX',233)+shadow.get('dx',0);meta['centerY']=meta.get('centerY',233)+shadow.get('dy',0);meta['blend']=0
                shadows.append(baker.sprite(folder,f'clock_shadow_{kind}.png',meta,f'face{i}_shadow_{kind}'))
            overlay=baker.sprite(folder,'clock_overlay.png',{'show':True,'centerX':0,'centerY':0},f'face{i}_overlay')
            texts=[]
            for slot in range(1,3):
                meta=style.get('text'+str(slot),{});name=f'face{i}_text{slot}';font_path=folder/f'font_clock{slot}.bin'
                if meta.get('show'):
                    content=windows_font('ARIALN.TTF',18) if i<2 and slot==1 else windows_font('consola.ttf',22) if i<2 else load_font(font_path)
                    emit_font(out,name,content)
                    texts.append('{'+f'&{name}Font,{json.dumps(meta.get("fmt",""))},{meta.get("x",233)},{meta.get("y",233)},{ink(meta.get("color",0xffffff))},{meta.get("opa",255)},{str(meta.get("upper",False)).lower()},{str(meta.get("curved",False)).lower()},{meta.get("curveR",150)},{meta.get("arcDeg",0)},{meta.get("align",1)}'+'}')
                else:texts.append('{}')
            order=hand.get('order',[3,4,0,1,2])
            descriptors.append('{'+f'{plate},'+'{'+','.join(sprites)+'},{'+','.join(shadows)+'},'+overlay+',{' +','.join(map(str,order))+'},{'+','.join(texts)+'},'+str(style.get('textOverHands',False)).lower()+','+json.dumps(label)+'}')
        out.write('const Face faces[FACE_COUNT]={\n'+',\n'.join(descriptors)+'\n};\n')
    if packed:
        (ROOT/'face-credits.json').write_text(json.dumps(credits,indent=2,ensure_ascii=False),encoding='utf-8')
        print(f'Baked {len(descriptors)} clock faces: {baker.total:,} compressed image bytes; {destination}')

if __name__=='__main__':build(True);build(False)
